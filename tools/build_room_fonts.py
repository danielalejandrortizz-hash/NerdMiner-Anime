#!/usr/bin/env python3
"""Bake antialiased sans-serif glyphs at the web's CSS pixel sizes (FreeType)."""
import argparse
import ctypes as C
from pathlib import Path

root = Path(__file__).resolve().parents[1]
class Generic(C.Structure):
    _fields_ = [('data', C.c_void_p), ('finalizer', C.c_void_p)]
class Vector(C.Structure):
    _fields_ = [('x', C.c_long), ('y', C.c_long)]
class BBox(C.Structure):
    _fields_ = [(n, C.c_long) for n in ['xmin','ymin','xmax','ymax']]
class Metrics(C.Structure):
    _fields_ = [(n, C.c_long) for n in ['width','height','hbx','hby','ha','vbx','vby','va']]
class Bitmap(C.Structure):
    _fields_ = [('rows',C.c_uint),('width',C.c_uint),('pitch',C.c_int),('buffer',C.POINTER(C.c_ubyte)),('grays',C.c_ushort),('mode',C.c_ubyte),('palette_mode',C.c_ubyte),('palette',C.c_void_p)]
class Slot(C.Structure):
    _fields_ = [('library',C.c_void_p),('face',C.c_void_p),('next',C.c_void_p),('index',C.c_uint),('generic',Generic),('metrics',Metrics),('linearH',C.c_long),('linearV',C.c_long),('advance',Vector),('format',C.c_uint),('bitmap',Bitmap),('left',C.c_int),('top',C.c_int)]
class Face(C.Structure):
    _fields_ = [(n,C.c_long) for n in ['faces','index','flags','style_flags','glyphs']] + [('family',C.c_char_p),('style',C.c_char_p),('fixed_sizes',C.c_int),('sizes',C.c_void_p),('charmaps_count',C.c_int),('charmaps',C.c_void_p),('generic',Generic),('bbox',BBox),('units',C.c_ushort)] + [(n,C.c_short) for n in ['ascender','descender','height','maxw','maxh','underline','thickness']] + [('glyph',C.POINTER(Slot))]

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font',default='/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf')
    args=parser.parse_args()
    ft=C.CDLL('libfreetype.so.6')
    lib=C.c_void_p(); assert ft.FT_Init_FreeType(C.byref(lib))==0
    face=C.POINTER(Face)()
    ft.FT_New_Face.argtypes=[C.c_void_p,C.c_char_p,C.c_long,C.c_void_p]
    assert ft.FT_New_Face(lib,str(Path(args.font)).encode(),0,C.byref(face))==0
    allchars=''.join(chr(c) for c in range(32,127))+'áéíóúñÁÉÍÓÚÑüÜ€£¥≥·—'
    numeric='0123456789:.,-/ %€$£¥TKMG<>e+'
    out=['// Generated by tools/build_room_fonts.py (DejaVu Sans, Bitstream Vera license).',
         '// Antialiased coverage, 4 bits per pixel. See artwork/fonts/DejaVu-LICENSE.txt.',
         '#pragma once',
         'struct RoomWebGlyph { uint32_t offset; uint16_t code; uint8_t w,h; int8_t x,y; uint8_t advance; };',
         'struct RoomWebFont { const uint8_t *pixels; const RoomWebGlyph *glyphs; uint16_t count; uint8_t size,baseline; };']
    for size in [4,5,6,8,10,21,27,34,46,62]:
        assert ft.FT_Set_Pixel_Sizes(face,0,size)==0
        glyphs=[];data=[]
        chars=allchars if size<=10 or size==27 else ':' if size==46 else numeric
        for ch in sorted(set(chars),key=ord):
            assert ft.FT_Load_Char(face,ord(ch),6)==0 # render, no grid fitting
            g=face.contents.glyph.contents;b=g.bitmap
            assert b.mode==2 and b.width<128 and b.rows<128
            coverage=[(b.buffer[y*b.pitch+x]+8)//17 for y in range(b.rows) for x in range(b.width)]
            glyphs.append((len(data),ord(ch),b.width,b.rows,g.left,-g.top,round(g.advance.x/64)))
            if len(coverage)%2:coverage.append(0)
            data.extend((coverage[i]<<4)|coverage[i+1] for i in range(0,len(coverage),2))
        out.append(f'static const uint8_t roomFont{size}Pixels[] PROGMEM = {{')
        out.extend(','.join(str(v) for v in data[i:i+40])+',' for i in range(0,len(data),40));out.append('};')
        out.append(f'static const RoomWebGlyph roomFont{size}Glyphs[] PROGMEM = {{')
        out.extend('{'+','.join(map(str,g))+'},' for g in glyphs);out.append('};')
        # CSS line-height: 1; center the em box using the face ascender ratio.
        baseline=round(size*(face.contents.ascender+face.contents.descender)/(2*face.contents.units)+size/2)
        out.append(f'static const RoomWebFont roomFont{size} = {{roomFont{size}Pixels,roomFont{size}Glyphs,{len(glyphs)},{size},{baseline}}};')
        print(f'{size}px: {len(glyphs)} glyphs, {len(data)} bytes')
    (root/'src/media/room/RoomWebFonts.h').write_text('\n'.join(out)+'\n')
    ft.FT_Done_Face(face);ft.FT_Done_FreeType(lib)
if __name__=='__main__':main()
