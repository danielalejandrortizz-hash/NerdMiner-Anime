#!/usr/bin/env python3
"""Compile the four original PNGs into 320x240 RGB565 flash assets (stdlib only)."""
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
NAMES = (("goku", "roomGoku"), ("saiyan", "roomSaiyan"),
         ("pikachu", "roomPikachu"), ("charmander", "roomCharmander"))


def decode_png(path):
    data = path.read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("Not a PNG")
    offset, compressed, width, height, channels = 8, bytearray(), 0, 0, 0
    while offset < len(data):
        length = struct.unpack_from(">I", data, offset)[0]
        kind = data[offset+4:offset+8]
        body = data[offset+8:offset+8+length]
        expected = struct.unpack_from(">I", data, offset+8+length)[0]
        if zlib.crc32(kind + body) & 0xffffffff != expected:
            raise ValueError("PNG CRC mismatch")
        offset += length + 12
        if kind == b"IHDR":
            width, height, depth, color, comp, filt, interlace = struct.unpack(">IIBBBBB", body)
            if depth != 8 or color not in (2, 6) or comp or filt or interlace:
                raise ValueError("Expected non-interlaced 8-bit RGB/RGBA PNG")
            channels = 3 if color == 2 else 4
        elif kind == b"IDAT":
            compressed.extend(body)
        elif kind == b"IEND":
            break
    raw = zlib.decompress(compressed)
    stride = width * channels
    if len(raw) != (stride + 1) * height:
        raise ValueError("Invalid PNG image length")
    pixels, prev = bytearray(), bytearray(stride)
    for y in range(height):
        at = y * (stride + 1)
        mode, row = raw[at], bytearray(raw[at+1:at+1+stride])
        if mode > 4:
            raise ValueError("Unknown PNG filter")
        for x in range(stride):
            left = row[x-channels] if x >= channels else 0
            up = prev[x]
            corner = prev[x-channels] if x >= channels else 0
            if mode == 1:
                predictor = left
            elif mode == 2:
                predictor = up
            elif mode == 3:
                predictor = (left + up) // 2
            elif mode == 4:
                p = left + up - corner
                a, b, c = abs(p-left), abs(p-up), abs(p-corner)
                predictor = left if a <= b and a <= c else up if b <= c else corner
            else:
                predictor = 0
            row[x] = (row[x] + predictor) & 255
        pixels.extend(row)
        prev = row
    return width, height, channels, pixels


def compile_pixels(width, height, channels, pixels):
    if width * 3 != height * 4 or width < 320 or height < 240:
        raise ValueError("Expected a 4:3 source at least 320x240")
    result = []
    for y in range(240):
        y0, y1 = y*height//240, (y+1)*height//240
        for x in range(320):
            x0, x1 = x*width//320, (x+1)*width//320
            red = green = blue = 0
            for sy in range(y0, y1):
                for sx in range(x0, x1):
                    i = (sy*width + sx)*channels
                    red += pixels[i]; green += pixels[i+1]; blue += pixels[i+2]
                    if channels == 4 and pixels[i+3] != 255:
                        raise ValueError("Scene images must be opaque")
            count = (x1-x0)*(y1-y0)
            red //= count; green //= count; blue //= count
            result.append(((red & 248) << 8) | ((green & 252) << 3) | (blue >> 3))
    return result


def main():
    target = ROOT / "src/media/room"
    target.mkdir(parents=True, exist_ok=True)
    for filename, symbol in NAMES:
        values = compile_pixels(*decode_png(ROOT / "artwork/ki-room" / (filename + "-sunset.png")))
        rows = [", ".join(f"0x{v:04x}" for v in values[i:i+16]) for i in range(0, len(values), 16)]
        text = "// Generated by tools/build_room_assets.py; do not edit.\n"
        text += f"const uint16_t {symbol}[320 * 240] PROGMEM = {{\n"
        text += ",\n".join(rows) + "\n};\n"
        (target / (filename + ".inc")).write_text(text)
        print(f"{filename}: {len(values)*2:,} flash bytes")


if __name__ == "__main__":
    main()
